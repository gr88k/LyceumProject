// Цвета которые светлые — для них нужна тёмная обводка
const LIGHT_COLORS = new Set([
    '#ffffff', '#fdd835', '#ffcc80', '#d7ccc8',
    '#f48fb1', '#cfd8dc', '#b39ddb', '#c0c0c0', '#64b5f6', '#80cbc4',
]);

// Применяет цвет к .color-dot элементам на странице
function applyColorDots() {
    document.querySelectorAll('.color-dot').forEach(dot => {
        const name = (dot.dataset.color || '').toLowerCase().trim();
        const css  = COLOR_MAP[name];
        if (css) {
            if (css.startsWith('linear-gradient')) {
                dot.style.background = css;
            } else {
                dot.style.backgroundColor = css;
                if (LIGHT_COLORS.has(css)) dot.style.borderColor = 'rgba(0,0,0,0.3)';
            }
        } else {
            // Английское название или hex — браузер разберётся сам
            dot.style.backgroundColor = name;
        }
    });
}

document.addEventListener('DOMContentLoaded', applyColorDots);